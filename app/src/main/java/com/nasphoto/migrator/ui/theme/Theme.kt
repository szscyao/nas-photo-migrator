/**
 * 应用主题（Material3，亮/暗双套）。
 *
 * 仅使用 Compose Material3，不在 XML 主题里定义颜色；
 * 状态栏/导航栏图标明暗跟随主题，保证深色模式下可读。
 */
@Composable
fun NasMigratorTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    content: @Composable () -> Unit,
) {
    val colorScheme = if (darkTheme) DarkColorScheme else LightColorScheme
    val view = LocalView.current
    if (!view.isInEditMode) {
        SideEffect {
            val window = (view.context as? Activity)?.window ?: return@SideEffect
            val controller = WindowCompat.getInsetsController(window, view)
            controller.isAppearanceLightStatusBars = !darkTheme
            controller.isAppearanceLightNavigationBars = !darkTheme
        }
    }
    MaterialTheme(
        colorScheme = colorScheme,
        typography = Typography(),
        content = content,
    )
}

/** 成功色（随亮/暗主题切换，供「已释放空间」「成功数」等语义展示使用） */
@Composable
fun successColor(): Color = if (isSystemInDarkTheme()) SuccessGreenDark else SuccessGreen

/** 警告色（随亮/暗主题切换，供暂停原因、低电量等展示使用） */
@Composable
fun warningColor(): Color = if (isSystemInDarkTheme()) WarningAmberDark else WarningAmber
