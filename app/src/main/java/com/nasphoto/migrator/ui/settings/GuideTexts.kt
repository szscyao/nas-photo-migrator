        本工具在前台服务中逐张迁移相册，系统若把应用「冻结」或断开网络，迁移会被暂停。
        以下设置可显著提升后台存活率（不同系统版本菜单名可能略有差异）：

        【华为 / 荣耀】
        1. 设置 → 应用 → 应用启动管理 → 找到本应用 → 关闭「自动管理」，
           并允许「自启动」「关联启动」「后台活动」；
        2. 设置 → 电池 → 更多电池设置 → 打开「休眠时始终保持网络连接」。

