        1. 设置 → 应用设置 → 应用管理 → 本应用 → 省电策略 → 选择「无限制」；
        2. 打开「自启动」；
        3. 在最近任务（多任务界面）中下拉本应用卡片加锁，防止被一键清理。

        【OPPO / 一加 / realme】
        1. 设置 → 电池 → 应用耗电管理 → 本应用 → 允许「后台运行」与「自启动」；
        2. 在最近任务界面给本应用加锁。

        【vivo / iQOO】
        1. 设置 → 电池 → 后台耗电管理 → 本应用 → 允许「后台高耗电」；
        2. 打开「自启动」与「关联启动」。

        【所有机型】
        设置 → 电池 → 电池优化 → 找到本应用 → 设为「不优化」（或使用本页「电池优化」按钮跳转）。

        说明：以上操作只影响系统对本应用的省电限制，不会改变迁移的串行与校验规则。
    """.trimIndent()
